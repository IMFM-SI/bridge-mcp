"""The π-Base domains of the `math_data` database: topological spaces, properties,
traits, and theorems. The tables are generated by `scripts/generate_pibase.py`."""

from bridge_mcp.mathql.database import Column, ForeignKey, Schema
from bridge_mcp.mathql.types import BoolType, IntType, ListType, ProductType, StringType, Ty


def _columns(
    rows: tuple[tuple[str, str, Ty, str], ...], primary: tuple[str, ...]
) -> dict[str, Column]:
    """The column mapping from (label, column, type, doc) rows."""
    return {
        label: Column(column, ty, label in primary, doc) for label, column, ty, doc in rows
    }


def _foreign_keys(rows: tuple[tuple[str, str, str, str], ...]) -> dict[str, ForeignKey]:
    """The foreign-key mapping from (label, column, domain, doc) rows; every foreign
    key among these domains points at the linked table's `uid`."""
    return {
        label: ForeignKey(domain, ((column, "uid"),), doc)
        for label, column, domain, doc in rows
    }


SPACE = Schema(
    table="pibase_space",
    columns=_columns(
        (
            ("uid", "uid", StringType(), "the space's identifier, e.g. 'S000026'"),
            ("name", "name", StringType(), "the space's name, in LaTeX-flavored text"),
            ("aliases", "aliases", ListType(StringType()), "alternative names"),
            (
                "description",
                "description",
                StringType(),
                "the definition, in LaTeX-flavored markdown",
            ),
            (
                "counterexamples_id",
                "counterexamples_id",
                IntType(),
                "the space's number in Counterexamples in Topology; undefined when absent",
            ),
            ("refs", "refs", ListType(StringType()), "literature references"),
        ),
        primary=("uid",),
    ),
    foreign_keys={},
    doc="A topological space from the π-Base community database.",
)

PROPERTY = Schema(
    table="pibase_property",
    columns=_columns(
        (
            ("uid", "uid", StringType(), "the property's identifier, e.g. 'P000016'"),
            ("name", "name", StringType(), "the property's name, in LaTeX-flavored text"),
            ("aliases", "aliases", ListType(StringType()), "alternative names"),
            (
                "description",
                "description",
                StringType(),
                "the definition, in LaTeX-flavored markdown",
            ),
            ("refs", "refs", ListType(StringType()), "literature references"),
        ),
        primary=("uid",),
    ),
    foreign_keys={},
    doc="A topological property, e.g. compactness.",
)

THEOREM = Schema(
    table="pibase_theorem",
    columns=_columns(
        (
            ("uid", "uid", StringType(), "the theorem's identifier, e.g. 'T000042'"),
            (
                "statement",
                "statement",
                StringType(),
                "the implication, rendered with property names",
            ),
            (
                "when_json",
                "when_json",
                StringType(),
                "the antecedent formula as JSON over property uids",
            ),
            (
                "then_json",
                "then_json",
                StringType(),
                "the consequent formula as JSON over property uids",
            ),
            ("description", "description", StringType(), "the proof or its citation"),
            ("refs", "refs", ListType(StringType()), "literature references"),
        ),
        primary=("uid",),
    ),
    foreign_keys={},
    doc="A theorem of π-Base: an implication between property values.",
)

TRAIT = Schema(
    table="pibase_trait",
    columns=_columns(
        (
            ("space_uid", "space", StringType(), "the space's uid"),
            ("property_uid", "property", StringType(), "the property's uid"),
            ("value", "value", BoolType(), "whether the property holds on the space"),
            (
                "asserted",
                "asserted",
                BoolType(),
                "asserted by π-Base, rather than derived by deduction",
            ),
            (
                "premises",
                "premises",
                ListType(ProductType((StringType(), BoolType()))),
                "the (property uid, value) premises of the final derivation step; "
                "empty when asserted",
            ),
            (
                "description",
                "description",
                StringType(),
                "π-Base's justification; empty when derived",
            ),
            ("refs", "refs", ListType(StringType()), "literature references"),
        ),
        primary=("space_uid", "property_uid"),
    ),
    foreign_keys=_foreign_keys(
        (
            ("space", "space", "Space", "the space"),
            ("property", "property", "Property", "the property"),
            (
                "theorem",
                "theorem",
                "Theorem",
                "the final derivation step's theorem; undefined when asserted",
            ),
        )
    ),
    doc="A property value of a space, asserted by π-Base or derived by deduction.",
)

DOMAINS = {"Space": SPACE, "Property": PROPERTY, "Trait": TRAIT, "Theorem": THEOREM}
