"""The `math_data` database: the `Graph` domain (all graphs on up to 8 vertices
plus Cayley graphs of the group census), the `Group` domain (schemas in
`groups.py`), the π-Base domains (schemas in `pibase.py`), and the provenance
domains (schemas in `provenance.py`). Generated by `bridge_mcp.generate`."""

from bridge_mcp.mathql.database import Column, Database, Example, ForeignKey, Schema
from bridge_mcp.mathql.databases import groups, pibase, provenance
from bridge_mcp.mathql.types import BoolType, IntType, ListType, StringType, Ty

_COLUMNS: tuple[tuple[str, Ty, str], ...] = (
    ("graph6", StringType(), "the graph in graph6 encoding (nauty's canonical form)"),
    ("num_vertices", IntType(), "order: the number of vertices"),
    ("num_edges", IntType(), "size: the number of edges"),
    ("degree_sequence", ListType(IntType()), "the vertex degrees, sorted descending"),
    ("min_degree", IntType(), "the smallest vertex degree"),
    ("max_degree", IntType(), "the largest vertex degree"),
    ("is_regular", BoolType(), "whether all vertices have the same degree"),
    ("num_components", IntType(), "the number of connected components"),
    ("is_connected", BoolType(), "whether the graph is connected"),
    (
        "diameter",
        IntType(),
        "the greatest distance between two vertices; undefined when disconnected",
    ),
    ("radius", IntType(), "the minimum vertex eccentricity; undefined when disconnected"),
    ("girth", IntType(), "the length of a shortest cycle; undefined when acyclic"),
    ("is_tree", BoolType(), "whether the graph is a tree"),
    ("is_forest", BoolType(), "whether the graph is a forest"),
    ("is_bipartite", BoolType(), "whether the graph is bipartite"),
    ("is_planar", BoolType(), "whether the graph is planar"),
    ("is_eulerian", BoolType(), "whether the graph has an Eulerian circuit"),
    ("num_triangles", IntType(), "the number of triangles (3-cliques)"),
    (
        "clique_number",
        IntType(),
        "the size of a largest clique; undefined for graphs on more than 8 vertices",
    ),
    (
        "independence_number",
        IntType(),
        "the size of a largest independent set; undefined for graphs on more than 8 vertices",
    ),
    (
        "chromatic_number",
        IntType(),
        "the chromatic number; undefined for graphs on more than 8 vertices",
    ),
    (
        "automorphism_count",
        IntType(),
        "the order of the automorphism group; undefined for graphs on more than 8 vertices",
    ),
)

_GRAPH = Schema(
    table="graph",
    columns={name: Column(name, ty, name == "graph6", doc) for name, ty, doc in _COLUMNS},
    foreign_keys={
        "source": ForeignKey("Source", (("source", "id"),), "who produced this row"),
        "automorphism_group": ForeignKey(
            "Group",
            (("aut_group_order", "order"), ("aut_group_index", "index")),
            "the automorphism group as a census group; undefined when its order "
            "exceeds 127 or the graph has more than 8 vertices",
        ),
    },
    doc=(
        "A finite simple graph, up to isomorphism: every graph on up to 8 vertices, "
        "and the Cayley graphs of the group census."
    ),
)

